/** Righe del glifo (7 stringhe da 5 caratteri) oppure null se il carattere non è mappato. */
export const getGlyph = (char: string): string[] | null => {
  const raw = GLYPHS[char] ?? GLYPHS[char.toUpperCase()];
  return raw ? raw.split("/") : null;
};
